/** Mois de a à b inclus (gère le passage d'une année à l'autre, ex. 10 → 3). */
export function mois(a: number, b: number): number[] {
  const out: number[] = [];
  let m = a;
  for (;;) {
    out.push(m);
    if (m === b) break;
    m = (m % 12) + 1;
  }
  return out;
}
const TOUTE_ANNEE = mois(1, 12);
const p = (zone: ZoneId, statut: StatutPresence, abondance: Abondance, m: number[] = TOUTE_ANNEE): Presence => ({
  zone,
  statut,
  abondance,
  mois: m,
});

